"""Сцена Щита: набор именованных тел.

Имя тела — его Label. Фазы добавляют свои тела сюда, каркас Прогона не меняется.
"""


def build(doc):
    """Добавляет тела сцены в doc и возвращает их списком."""
    stub = doc.addObject("Part::Cylinder", "Stub")
    stub.Label = "Заглушка"  # временная, фаза 1 заменит Датчиком
    stub.Radius = 30
    stub.Height = 60
    return [stub]
