"""Параметры Скелета Щита, мм: все Стыки и общие размеры.

Система координат Щита: начало — Точка подвеса, центр верха Крышки; Z — вверх
по оси Щита; Откос — в −X, его плоскость параллельна YZ. Стопка растёт вниз
от Крышки: Крышка, Тарелка 1…, Нижняя Тарелка.

Детали читают параметры при вызове (params.X), а не копируют при импорте:
так тест подменяет число и перестраивает тела. Выводимые параметры — функции
внизу файла: код их только считает, ничего не подгоняет.
"""
import math

import FreeCAD

from sensor import params as sensor_params  # лист: сам ничего не импортирует

# Тарелка: плоская Полка у отверстия, от наружного края Полки вниз и наружу —
# конус. Профиль — по мотивам SanglierLab (Gill-экран). Печать вверх дном,
# Полкой на стол, без поддержек.
# наружный Ø: Полка r62 плюс вынос конуса 15. Тень при шаге 16 и стенке 2
# есть с выноса ≈ 13.2 (подъём + толщина стенки по вертикали > шага)
DISH_DIAMETER = 154
DISH_HOLE_DIAMETER = 76  # по нижнему краю Капельника: Датчик с Держателем в плане — радиус 27.6, плюс зазор 10
SHELF_RADIUS = 62  # наружный радиус Полки: Стойка r56 с бобышкой Ø10 и 1 мм до края
# угол конуса к горизонтали, градусы: печать без поддержек; круче ≈ 46°
# просвет по конусу при шаге 16 станет меньше 9
CONE_ANGLE = 45
DISH_WALL = 2  # толщина Полки по вертикали и конуса по нормали
# Капельник: с края Полки вниз и внутрь, как у SanglierLab; стенка DISH_WALL
# по нормали. Ø отверстия — по его нижнему краю. Наклон внутренней стороны
# atan((DISH_WALL + DRIP_DROP) / DRIP_INSET) ≈ 47.5° к горизонтали: печать без поддержек
DRIP_DROP = 4  # низ Капельника ниже низа Полки
DRIP_INSET = 5.5  # нижний край Капельника внутрь от края Полки
DISH_PITCH = 16  # шаг стопки по Z, SanglierLab
DISH_COUNT = 6  # N: Тарелки вместе с Нижней, без Крышки; наименьшее, при котором проходит зазор Заглушки

# Стойки: выступы заодно с Тарелкой, свисают с её Полки на Полку нижней
# Тарелки; сквозь Полки и Стойки — отверстие под Шпильку.
STANDOFF_COUNT = 4
STANDOFF_RADIUS = 56  # ось Стойки от оси Щита: снаружи резьбового кольца (49) с местом под шайбу M4
STANDOFF_ANGLE = 45  # градусы от +X до первой Стойки: ни одна не смотрит на Откос
STANDOFF_DIAMETER = 10  # Ø Стойки
STUD_HOLE_DIAMETER = 4.5  # под Шпильку M4, зазор 0.25 на сторону

# Стык Крышка↔Кронштейн: болт M6 по оси Щита через Точку подвеса.
HANG_BOLT_DIAMETER = 6  # M6
SPACER_HEIGHT = 20  # проставка между верхом Крышки и консолью Кронштейна

# Стык Щит↔Откос.
JAMB_TO_DISH = 150  # от кирпича Откоса до края Тарелок, по X

# Стык Нижняя Тарелка↔Дно: резьбовое кольцо снизу Нижней Тарелки, Дно
# навинчивается в него. Витков в Скелете нет, их делают фазы 3 и 5.
THREAD_DIAMETER = 90  # внутренний Ø кольца
THREAD_PITCH = 5
# наклон боковой стороны к плоскости, перпендикулярной оси; полный угол
# профиля 90°; как `angle` в threads.scad SanglierLab. Градусы
THREAD_FLANK_SLOPE = 45
THREAD_DEPTH = 1.5  # глубина зуба; SanglierLab ≈1.56, проверено их печатью
THREAD_CHAMFER = 1  # фаска захода, × 45°
THREAD_LENGTH = 15  # по Z, от низа Нижней Тарелки у кольца
# по нормали к профилю, на наружной резьбе. Ориентир SanglierLab (≈0.44 по
# нормали к стороне, ≈0.6 на вершине) с запасом, без печати Пробника; не
# подошло — перепечатать Дно
THREAD_CLEARANCE = 0.5
THREAD_RING_WALL = 4  # стенка кольца под витки и за ними

# Держатель: вертикальная пластина на Дне за Корпусом (−X), наверху Крючок —
# стержень Ø стержня крючка Вешалки через отверстие Ушка.
HOLDER_THICKNESS = 3  # по X
HOLDER_WIDTH = 20  # по Y; пластина Вешалки — 18

# Кронштейн: Г-образный, покупной. Пластина — на плоскости Откоса, вниз от
# консоли; консоль — над Крышкой на высоте проставки, от пластины за ось Щита
# на половину своей ширины (болт по оси — посередине конца консоли).
# Сечения — до обмера покупного.
BRACKET_PLATE_THICKNESS = 4  # по X, до обмера покупного
BRACKET_PLATE_WIDTH = 30  # по Y, до обмера покупного
BRACKET_PLATE_HEIGHT = 100  # по Z, от верха консоли вниз, до обмера покупного
BRACKET_ARM_THICKNESS = 4  # по Z, до обмера покупного
BRACKET_ARM_WIDTH = 30  # по Y, до обмера покупного

# Зазоры.
PLUG_MIN_GAP = 10  # воздух вокруг Заглушки до любого тела, кроме Держателя
NOSE_TO_FLOOR_GAP = 10  # низ Носика над верхом Дна
HOOK_TO_LID_GAP = 10  # верх Крючка под Крышкой, не меньше
DISH_MIN_CLEARANCE = 9  # просвет между соседними Тарелками, без Стоек; SanglierLab ≈ 8.5


# Выводимые параметры.

def cone_run():
    """Вынос конуса в плане: от наружного края Полки до наружного края Тарелки.

    Полка не помещается в Ø Тарелки (вынос ≤ 0) — ValueError с Ø и радиусом Полки.
    """
    run = DISH_DIAMETER / 2 - SHELF_RADIUS
    if run <= 0:
        raise ValueError(
            f"Ø Тарелки {DISH_DIAMETER:g} мм: Полка r{SHELF_RADIUS:g} не помещается"
            f" — вынос конуса {run:.2f} мм, нужен Ø больше {2 * SHELF_RADIUS:g} мм",
        )
    return run


def cone_rise():
    """Подъём конуса: от его наружного края до Полки, по Z."""
    return cone_run() * math.tan(math.radians(CONE_ANGLE))


def cone_wall_height():
    """Толщина стенки конуса по вертикали: DISH_WALL по нормали к конусу."""
    return DISH_WALL / math.cos(math.radians(CONE_ANGLE))


def dish_top(index):
    """Z верха Полки Тарелки index: 0 — Крышка, DISH_COUNT — Нижняя Тарелка."""
    return -index * DISH_PITCH


def stack_height():
    """От Точки подвеса до низа наружного края Нижней Тарелки."""
    return -dish_top(DISH_COUNT) + cone_rise() + cone_wall_height()


def floor_top():
    """Z верха Дна: низ Полки Нижней Тарелки, откуда вниз выходит резьбовое кольцо."""
    return dish_top(DISH_COUNT) - DISH_WALL


def bracket_reach():
    """Вылет Кронштейна: от Откоса до оси Щита, по X."""
    return JAMB_TO_DISH + DISH_DIAMETER / 2


def jamb_x():
    """X плоскости Откоса."""
    return -bracket_reach()


def sensor_shift():
    """Перенос Датчика из его системы координат в Щит, только сдвиг.

    Ось Носика — на оси Щита, низ Носика — на NOSE_TO_FLOOR_GAP выше Дна.
    """
    nose_bottom = (
        sensor_params.CASE_Z
        - sensor_params.CASE_DIAMETER / 2
        - sensor_params.NOSE_LENGTH
    )
    z = floor_top() + NOSE_TO_FLOOR_GAP - nose_bottom
    return FreeCAD.Vector(-sensor_params.NOSE_X, 0, z)
