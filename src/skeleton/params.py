"""Параметры Скелета Щита, мм: все Стыки и общие размеры.

Система координат Щита: начало — Точка подвеса, центр верха Крышки; Z — вверх
по оси Щита; Откос — в −X, его плоскость параллельна YZ. Стопка растёт вниз
от Крышки: Крышка, Тарелка 1…, Нижняя Тарелка.

Детали читают параметры при вызове (params.X), а не копируют при импорте:
так тест подменяет число и перестраивает тела. Выводимые параметры — функции
внизу файла: код их только считает, ничего не подгоняет.
"""
import math

import FreeCAD

from sensor import params as sensor  # лист: сам ничего не импортирует

# Тарелка: коническая оболочка, наружный край внизу, край отверстия наверху.
# Профиль — от SanglierLab (Gill-экран).
DISH_DIAMETER = 140  # наружный Ø; больше ориентира ТЗ 110–120: Датчик — шайба шириной 50
DISH_HOLE_DIAMETER = 76  # Датчик с Держателем в плане — радиус 27.6, плюс зазор 10
DISH_PITCH = 16  # шаг стопки по Z, SanglierLab
DISH_RISE = 23  # подъём конуса от наружного края до края отверстия, SanglierLab
DISH_WALL = 2  # толщина стенки по нормали к конусу
DISH_COUNT = 6  # N: Тарелки вместе с Нижней, без Крышки; по высоте Датчика

# Стойки: бобышки заодно с Тарелкой, от неё вверх до соседней Тарелки;
# сквозь все Тарелки и Крышку — отверстие под Шпильку.
STANDOFF_COUNT = 4
STANDOFF_RADIUS = 46  # ось Стойки от оси Щита: между отверстием (38) и краем (70)
STANDOFF_ANGLE = 45  # градусы от +X до первой Стойки: ни одна не смотрит на Откос
STANDOFF_DIAMETER = 10  # бобышка
STUD_HOLE_DIAMETER = 4.5  # под Шпильку M4, зазор 0.25 на сторону

# Стык Крышка↔Кронштейн: болт M6 по оси Щита через Точку подвеса.
HANG_BOLT_DIAMETER = 6  # M6
SPACER_HEIGHT = 20  # проставка между верхом Крышки и консолью Кронштейна

# Стык Щит↔Откос.
JAMB_TO_DISH = 150  # от кирпича Откоса до края Тарелок, по X

# Кронштейн: Г-образный, покупной. Пластина — на плоскости Откоса, вниз от
# консоли; консоль — над Крышкой на высоте проставки, от пластины за ось Щита
# на половину своей ширины (болт по оси — посередине конца консоли).
# Сечения — до обмера покупного.
BRACKET_PLATE_THICKNESS = 4  # по X, до обмера покупного
BRACKET_PLATE_WIDTH = 30  # по Y, до обмера покупного
BRACKET_PLATE_HEIGHT = 100  # по Z, от верха консоли вниз, до обмера покупного
BRACKET_ARM_THICKNESS = 4  # по Z, до обмера покупного
BRACKET_ARM_WIDTH = 30  # по Y, до обмера покупного

# Зазоры.
PLUG_MIN_GAP = 10  # воздух вокруг Заглушки до любого тела, кроме Держателя


# Выводимые параметры.

def dish_wall_height():
    """Толщина стенки Тарелки по вертикали: DISH_WALL по нормали к конусу."""
    run = (DISH_DIAMETER - DISH_HOLE_DIAMETER) / 2
    return DISH_WALL * math.hypot(run, DISH_RISE) / run


def dish_top(index):
    """Z края отверстия Тарелки index: 0 — Крышка, DISH_COUNT — Нижняя Тарелка."""
    return -index * DISH_PITCH


def stack_height():
    """От Точки подвеса до низа наружного края Нижней Тарелки."""
    return -dish_top(DISH_COUNT) + DISH_RISE + dish_wall_height()


def bracket_reach():
    """Вылет Кронштейна: от Откоса до оси Щита, по X."""
    return JAMB_TO_DISH + DISH_DIAMETER / 2


def jamb_x():
    """X плоскости Откоса."""
    return -bracket_reach()


def sensor_shift():
    """Перенос Датчика из его системы координат в Щит, только сдвиг.

    Ось Носика — на оси Щита. Пока нет Дна, по Z: верх Заглушки (верх Ушка)
    на PLUG_MIN_GAP ниже Крышки.
    """
    plug_top = sensor.EAR_OUTER_DIAMETER / 2
    z = -dish_wall_height() - PLUG_MIN_GAP - plug_top
    return FreeCAD.Vector(-sensor.NOSE_X, 0, z)
